// Renders the RaptHooker icon to a small baseline JPEG and writes it as a C array for the firmware.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

const repo = process.argv[2];
const out = process.argv[3];
const size = Number(process.argv[4] ?? 96);
const require = createRequire(join(repo, 'src', 'server', 'package.json'));
const { Resvg, initWasm } = require('@resvg/resvg-wasm');
const jpeg = require('jpeg-js');

await initWasm(readFileSync(require.resolve('@resvg/resvg-wasm/index_bg.wasm')));
let svg = readFileSync(join(repo, 'src', 'web', 'public', 'icons', 'icon.svg'), 'utf8');
// The screen background is black, so draw the rounded tile on black rather than transparent.
svg = svg.replace('<defs>', '<rect width="512" height="512" fill="#000"/><defs>');
const png = new Resvg(svg, { fitTo: { mode: 'width', value: size } }).render();
const { width, height, pixels } = png;
const data = Buffer.alloc(width * height * 4);
for (let i = 0; i < width * height; i++) {
  const a = pixels[i * 4 + 3] / 255;
  data[i * 4] = Math.round(pixels[i * 4] * a);
  data[i * 4 + 1] = Math.round(pixels[i * 4 + 1] * a);
  data[i * 4 + 2] = Math.round(pixels[i * 4 + 2] * a);
  data[i * 4 + 3] = 255;
}
const jpg = jpeg.encode({ data, width, height }, 88).data;
const bytes = [...jpg].map((b) => `0x${b.toString(16).padStart(2, '0')}`);
const lines = [];
for (let i = 0; i < bytes.length; i += 16) lines.push('  ' + bytes.slice(i, i + 16).join(', '));
writeFileSync(
  out,
  `// Generated by tools/logo.mjs from src/web/public/icons/icon.svg. Do not edit.\n#pragma once\n#include <Arduino.h>\n\n` +
    `static const uint16_t LOGO_SIZE = ${size};\nstatic const uint8_t LOGO_JPG[] PROGMEM = {\n${lines.join(',\n')}\n};\n`,
);
console.log(`logo ${width}x${height} -> ${jpg.length} bytes`);
